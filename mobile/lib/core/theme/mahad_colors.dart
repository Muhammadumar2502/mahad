    if (p >= pass) return (fg: okText, soft: okSoft, ringStart: ringOkStart, ringEnd: ringOkEnd);
    if (p >= pass / 2) return (fg: warnText, soft: warnSoft, ringStart: ringWarnStart, ringEnd: ringWarnEnd);
    return (fg: badText, soft: badSoft, ringStart: ringBadStart, ringEnd: ringBadEnd);
  }

